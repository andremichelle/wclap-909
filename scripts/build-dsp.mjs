// Builds the DSP: embeds the samples, compiles dsp/assembly with AssemblyScript and writes public/module.wasm.
// The function table is renamed to __indirect_function_table, the name WebCLAP hosts look for.
//
// node scripts/build-dsp.mjs [--debug]

import {readdirSync, readFileSync, writeFileSync, mkdirSync} from "node:fs"
import {dirname, join, resolve} from "node:path"
import {fileURLToPath} from "node:url"
import asc from "assemblyscript/asc"
import binaryen from "binaryen"

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const debug = process.argv.includes("--debug")

// Samples: 32-bit float, 44.1 kHz, mono. One data segment, each sample aligned to 16 bytes.
const resources = join(root, "dsp/resources")
const bytes = []
const lines = []
for (const file of readdirSync(resources).filter(name => name.endsWith(".raw")).sort()) {
    while (bytes.length % 16 !== 0) bytes.push(0)
    const data = readFileSync(join(resources, file))
    const name = file.replace(/\.raw$/, "").replace(/-/g, "_").toUpperCase()
    lines.push(`export const ${name}: usize = DATA + ${bytes.length}`)
    lines.push(`export const ${name}_LENGTH: i32 = ${data.length >> 2}`)
    for (const byte of data) bytes.push(byte)
}
writeFileSync(join(root, "dsp/assembly/samples.ts"),
    `// Generated by scripts/build-dsp.mjs from dsp/resources, do not edit\n\n` +
    `const DATA: usize = memory.data<u8>([${bytes.join(",")}], 16)\n\n${lines.join("\n")}\n`)

const outFile = join(root, "public/module.wasm")
mkdirSync(dirname(outFile), {recursive: true})
const {error, stderr} = await asc.main([
    "dsp/assembly/index.ts",
    "--outFile", "build/dsp/raw.wasm",
    "--textFile", "build/dsp/raw.wat",
    "--runtime", "stub",
    "--exportTable",
    "--exportStart", "_initialize",
    "--use", "abort=dsp/assembly/index/onAbort",
    "--initialMemory", "32",
    ...(debug ? ["--debug", "--sourceMap"] : ["-O3", "--noAssert"])
], {stdout: process.stdout, stderr: process.stderr})
if (error) {
    console.error(stderr.toString())
    process.exit(1)
}

const module = binaryen.readBinary(readFileSync(join(root, "build/dsp/raw.wasm")))
module.setFeatures(binaryen.Features.All)
module.removeExport("table")
module.addTableExport("0", "__indirect_function_table")
module.removeExport("onAbort")
if (!module.validate()) process.exit(1)
writeFileSync(outFile, module.emitBinary())
console.log(`module.wasm ${(readFileSync(outFile).length / 1024).toFixed(0)} kB`)
